import { useState } from "react";
import { motion, useReducedMotion } from "motion/react";
import { ArrowDownToLine, ArrowUpRight, Bookmark, Check, ChevronRight, CircleGauge, Clock3, Link2, ShieldCheck, Zap } from "lucide-react";
import { Tabs, TabsIndicator, TabsList, TabsPanel, TabsTab } from "@ui-sdk/react/tabs";
import { Toggle } from "@ui-sdk/react/toggle";
import { Popover, PopoverContent, PopoverDescription, PopoverTitle, PopoverTrigger } from "@ui-sdk/react/popover";
import { toast } from "@ui-sdk/react/toast";
import type { Report } from "@contracts/types";
import { trpc } from "@/providers/trpc";
import { Jim } from "./Jim";
import { ReportChart } from "./ReportChart";

function reportMarkdown(report: Report) {
  const content = report.content;
  return `# ${report.title}\n\n${content.executiveSummary}\n\n## Key metrics\n\n${content.metrics.map((metric) => `- **${metric.label}: ${metric.value}** (${metric.delta}) — ${metric.note}`).join("\n")}\n\n## Insights\n\n${content.insights.map((insight) => `### ${insight.title}\n${insight.detail}`).join("\n\n")}\n\n## Recommended actions\n\n${content.actions.map((action, index) => `${index + 1}. **${action.title}** — ${action.detail} (Impact: ${action.impact}; effort: ${action.effort})`).join("\n")}\n\n---\nGenerated by Project Jimvis. Prototype analysis with illustrative figures.\n`;
}

function Metrics({ report }: { report: Report }) {
  const reduceMotion = useReducedMotion();
  return (
    <div className="metric-grid">
      {report.content.metrics.map((metric, index) => (
        <motion.div
          className="metric"
          key={metric.label}
          initial={reduceMotion ? false : { opacity: 0, y: 18 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ delay: 0.08 * index, duration: 0.45 }}
        >
          <span className="metric__label">{metric.label}</span>
          <strong>{metric.value}</strong>
          <span className={`metric__delta metric__delta--${metric.trend}`}>{metric.delta}</span>
          <small>{metric.note}</small>
        </motion.div>
      ))}
    </div>
  );
}

function Insights({ report }: { report: Report }) {
  return (
    <div className="insight-list">
      {report.content.insights.map((insight, index) => (
        <motion.article
          className="insight-row"
          key={insight.title}
          initial={{ opacity: 0, x: -14 }}
          animate={{ opacity: 1, x: 0 }}
          transition={{ delay: 0.12 + index * 0.08 }}
        >
          <span className={`signal-dot signal-dot--${insight.signal}`} aria-hidden="true" />
          <div><h3>{insight.title}</h3><p>{insight.detail}</p></div>
          <span className="insight-index">0{index + 1}</span>
        </motion.article>
      ))}
    </div>
  );
}

function Segments({ report }: { report: Report }) {
  return (
    <div className="segment-list">
      {report.content.segments.map((segment, index) => (
        <div className="segment" key={segment.label}>
          <div className="segment__top"><strong>{segment.label}</strong><span>{segment.value}%</span></div>
          <div className="segment__track"><motion.i initial={{ scaleX: 0 }} animate={{ scaleX: segment.value / 100 }} transition={{ delay: index * 0.1, duration: 0.6 }} /></div>
          <p>{segment.detail}</p>
        </div>
      ))}
    </div>
  );
}

function Sources({ report }: { report: Report }) {
  return (
    <div className="source-list">
      {report.content.sources.map((source, index) => (
        <div className="source-row" key={source.title}>
          <span className="source-number">0{index + 1}</span>
          <div><strong>{source.title}</strong><p>{source.note}</p></div>
          <span className="source-type">{source.type}</span>
        </div>
      ))}
      <p className="source-disclosure"><ShieldCheck size={16} aria-hidden="true" />This prototype uses illustrative figures rather than connected company data.</p>
    </div>
  );
}

export function ReportView({ report, onFollowUp }: { report: Report; onFollowUp: (prompt: string) => void }) {
  const utils = trpc.useUtils();
  const reduceMotion = useReducedMotion();
  const [shareOpen, setShareOpen] = useState(false);
  const save = trpc.report.save.useMutation({
    onSuccess: async (updated) => {
      await utils.report.list.invalidate();
      await utils.report.get.setData({ id: updated.id }, updated);
      toast.success(updated.isSaved ? "Saved to your best thinking" : "Removed from saved reports");
    },
    onError: () => toast.error("Jim couldn’t save that change. Try again."),
  });

  const exportReport = () => {
    const blob = new Blob([reportMarkdown(report)], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `${report.title.toLowerCase().replace(/[^a-z0-9]+/g, "-")}.md`;
    link.click();
    URL.revokeObjectURL(url);
    toast.success("Report exported as Markdown");
  };

  const copyLink = async () => {
    try {
      await navigator.clipboard.writeText(window.location.href);
      toast.success("Private report link copied");
    } catch {
      toast.error("Copy the link from your address bar instead");
    } finally {
      setShareOpen(false);
    }
  };

  return (
    <motion.article className="report-view" key={report.id} initial={{ opacity: 0 }} animate={{ opacity: 1 }}>
      <motion.div
        className="chat-user-turn"
        initial={reduceMotion ? false : { opacity: 0, y: 10 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ duration: 0.35, ease: [0.22, 1, 0.36, 1] }}
      >
        <div className="chat-user-bubble">
          <span className="chat-turn-label">YOU ASKED</span>
          <p>{report.prompt}</p>
        </div>
      </motion.div>

      <motion.div
        className="assistant-intro"
        initial={reduceMotion ? false : { opacity: 0, y: 10 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ delay: 0.06, duration: 0.35, ease: [0.22, 1, 0.36, 1] }}
      >
        <Jim size="small" mood="success" interactive />
        <div><strong>Here’s the signal, without the noise.</strong><span>Built from your brief in four analytical passes.</span></div>
      </motion.div>

      <header className="report-header">
        <div className="report-kicker"><span>{report.category}</span><i /><span>Illustrative brief</span></div>
        <h1>{report.title}</h1>
        <div className="report-meta"><Clock3 size={14} aria-hidden="true" />{new Intl.DateTimeFormat("en", { month: "short", day: "numeric", hour: "numeric", minute: "2-digit" }).format(report.createdAt)}<span>·</span>Prepared by Jim</div>
        <div className="report-actions">
          <Toggle className="secondary-action" pressed={report.isSaved} onPressedChange={(pressed) => save.mutate({ id: report.id, saved: pressed })} disabled={save.isPending} aria-label="Save report">
            <Bookmark size={16} fill={report.isSaved ? "currentColor" : "none"} aria-hidden="true" />{report.isSaved ? "Saved" : "Save"}
          </Toggle>
          <Popover open={shareOpen} onOpenChange={setShareOpen}>
            <PopoverTrigger className="secondary-action"><Link2 size={16} aria-hidden="true" />Share</PopoverTrigger>
            <PopoverContent align="start" className="share-popover">
              <PopoverTitle>Share this brief</PopoverTitle>
              <PopoverDescription>Copy a private link for someone with access to this workspace.</PopoverDescription>
              <button className="primary-button" type="button" onClick={copyLink}><Link2 size={15} />Copy private link</button>
            </PopoverContent>
          </Popover>
          <button className="secondary-action" type="button" onClick={exportReport}><ArrowDownToLine size={16} aria-hidden="true" />Export</button>
        </div>
      </header>

      <Tabs defaultValue="overview" className="report-tabs">
        <TabsList aria-label="Report sections" className="report-tabs__list">
          <TabsTab value="overview"><CircleGauge size={15} aria-hidden="true" />Overview</TabsTab>
          <TabsTab value="analysis"><Zap size={15} aria-hidden="true" />Analysis</TabsTab>
          <TabsTab value="actions"><Check size={15} aria-hidden="true" />Actions <span className="tab-count">3</span></TabsTab>
          <TabsIndicator className="report-tabs__indicator" />
        </TabsList>

        <TabsPanel value="overview" className="report-panel">
          <section className="executive-summary">
            <span className="section-label">The short version</span>
            <p>{report.content.executiveSummary}</p>
          </section>
          <Metrics report={report} />
          <section className="report-section">
            <div className="section-heading"><div><span className="section-label">Signal over time</span><h2>{report.content.kind === "retention" ? "Activation bends the retention curve" : report.content.kind === "market" ? "Focused entry compounds faster" : "Momentum is building, unevenly"}</h2></div><span className="data-badge">6 periods</span></div>
            <ReportChart series={report.content.series} kind={report.content.kind} />
          </section>
          <section className="report-section">
            <div className="section-heading"><div><span className="section-label">What Jim noticed</span><h2>Three things worth your attention</h2></div></div>
            <Insights report={report} />
          </section>
        </TabsPanel>

        <TabsPanel value="analysis" className="report-panel">
          <section className="report-section report-section--first">
            <div className="section-heading"><div><span className="section-label">Comparative model</span><h2>Read the pattern, not just the number</h2></div></div>
            <ReportChart series={report.content.series} kind={report.content.kind} />
          </section>
          <section className="report-section">
            <div className="section-heading"><div><span className="section-label">Contribution mix</span><h2>Where the movement comes from</h2></div></div>
            <Segments report={report} />
          </section>
          <section className="report-section">
            <div className="section-heading"><div><span className="section-label">Evidence trail</span><h2>What sits behind the brief</h2></div></div>
            <Sources report={report} />
          </section>
        </TabsPanel>

        <TabsPanel value="actions" className="report-panel">
          <section className="actions-intro"><span className="section-label">From insight to movement</span><h2>Do these next.</h2><p>Three focused moves, ordered by leverage rather than volume.</p></section>
          <div className="action-list">
            {report.content.actions.map((action, index) => (
              <article className="action-card" key={action.title}>
                <span className="action-number">0{index + 1}</span>
                <div className="action-card__body"><h3>{action.title}</h3><p>{action.detail}</p><div className="action-tags"><span>Impact · {action.impact}</span><span>Effort · {action.effort}</span></div></div>
                <button type="button" className="followup-button" onClick={() => onFollowUp(`Create an implementation plan for “${action.title}” based on my ${report.category.toLowerCase()} report.`)}>Plan with Jim<ArrowUpRight size={16} aria-hidden="true" /></button>
              </article>
            ))}
          </div>
          <button className="next-question" type="button" onClick={() => onFollowUp(`What assumptions should I pressure-test before acting on this ${report.category.toLowerCase()} report?`)}><span>Not ready to act?</span><strong>Ask Jim to pressure-test the brief</strong><ChevronRight size={20} aria-hidden="true" /></button>
        </TabsPanel>
      </Tabs>
    </motion.article>
  );
}
